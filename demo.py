def sum_meal_nutrition(name):
    """拆包套餐组成，逐项在营养表求和，返回 (kcal, protein, fat, carb) 或 None"""
    items = MEAL_COMPOSITION.get(name)
    if not items:
        return None
    kcal = protein = fat = carb = 0
    missing = False
    for item_name, qty in items:
        nutr = NUTRITION.get(item_name)
        if nutr is None:
            missing = True
            continue
        kcal += nutr[0] * qty
        protein += nutr[1] * qty
        fat += nutr[2] * qty
        carb += nutr[3] * qty
    if missing:
        return None
    return (kcal, protein, fat, carb)


