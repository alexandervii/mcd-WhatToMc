def recommend(price_max=None, kcal_max=None, taste=None, goal=None, meal_type=None, top=5):
    """按条件筛选并排序餐品"""
    results = []
    for name, (price, tags, cat) in MENU.items():
        # 价格过滤
        if price_max is not None and price > price_max:
            continue
        # 营养数据匹配（名称精确或模糊）
        nutr = NUTRITION.get(name)
        if nutr is None and ("套餐" in name or "三件套" in name or "套" in name):
            # 套餐：优先拆包组成项求和（不能用单品的模糊匹配值）
            nutr = sum_meal_nutrition(name)
        if nutr is None:
            # 单品模糊匹配：去掉"三件套/套餐/精选"后缀
            base = name.replace("三件套", "").replace("套餐", "").replace("精选", "")
            nutr = NUTRITION.get(base)
        kcal, protein, fat, carb = nutr if nutr else (None, None, None, None)
        # 热量过滤（套餐营养未知则跳过热量硬过滤，标注未知）
        if kcal_max is not None and kcal is not None and kcal > kcal_max:
            continue
        # 口味关键词（名称 + tags 双重匹配）
        if taste:
            t = taste.lower()
            tagstr = " ".join(tags)
            name_hit = (
                (t == "牛肉" and ("牛肉" in name or "牛" in name or "巨无霸" in name or "吉士" in name or "安格斯" in name))
                or (t == "鸡肉" and "鸡" in name)
                or (t == "鱼" and "鱼" in name)
                or (t == "辣" and "辣" in name)
            )
            tag_hit = (
                (t == "牛肉" and ("牛肉" in tagstr or "安格斯" in tagstr))
                or (t == "鸡肉" and "鸡" in tagstr)
                or (t == "鱼" and "鱼" in tagstr)
                or (t == "辣" and "辣" in tagstr)
            )
            if not (name_hit or tag_hit):
                continue
        # 套餐类型
        if meal_type == "套餐" and "套餐" not in name and "三件套" not in name:
            continue
        if meal_type == "单品" and ("套餐" in name or "三件套" in name):
            continue

        # 打分：营养目标加分 + 正餐优先
        score = 0
        # 正餐（汉堡/套餐/堡/卷/饭）权重，避免全是零食饮品
        if any(k in name for k in ["堡", "套餐", "三件套", "卷", "鸡", "鱼", "饭"]):
            score += 100
        if goal == "高蛋白" and protein is not None:
            score += protein * 3
        if goal == "低脂" and fat is not None:
            score += (50 - fat) * 2
        if goal == "低卡" and kcal is not None:
            score += (1000 - kcal) // 10

        results.append({
            "name": name,
            "price": price,
            "kcal": kcal,
            "protein": protein,
            "fat": fat,
            "carb": carb,
            "tags": tags,
            "cat": cat,
            "score": score,
        })

    # 排序：按综合分数（含正餐权重），无 goal 时也优先正餐
    results.sort(key=lambda x: -x["score"])
    return results[:top]


