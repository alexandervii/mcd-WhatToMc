        p = f"{r['protein']}g" if r["protein"] is not None else "-"
        c = f"{r['carb']}g" if r["carb"] is not None else "-"
        f = f"{r['fat']}g" if r["fat"] is not None else "-"
        print(f"{r['name']:<22}{'¥'+str(r['price']):>6}{kcal:>10}{p:>9}{c:>8}{f:>8}")


